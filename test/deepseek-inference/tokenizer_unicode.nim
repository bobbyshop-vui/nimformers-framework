proc inRanges(cp: int, ranges: openArray[(int, int)]): bool =
  var lo = 0
  var hi = ranges.len
  while lo < hi:
    let mid = (lo + hi) div 2
    if cp < ranges[mid][0]: hi = mid
    elif cp > ranges[mid][1]: lo = mid + 1
    else: return true

proc unicodeSpace*(cp: int): bool =
  cp in 9..13 or cp in [0x20, 0x85, 0xa0, 0x1680, 0x2028, 0x2029, 0x202f, 0x205f, 0x3000] or cp in 0x2000..0x200a

proc unicodeCategory*(cp: int, category: string): bool =
  case category
  of "L", "Letter": inRanges(cp, CategoryL)
  of "M", "Mark": inRanges(cp, CategoryM)
  of "N", "Number": inRanges(cp, CategoryN)
  of "P", "Punctuation": inRanges(cp, CategoryP)
  of "S", "Symbol": inRanges(cp, CategoryS)
  of "Z", "Separator": inRanges(cp, CategoryZ)
  of "C", "Other": inRanges(cp, CategoryC)
  of "Nd", "Decimal_Number":
    inRanges(cp, CategoryNd)
  of "White_Space", "space", "s": unicodeSpace(cp)
  of "word", "w": inRanges(cp, CategoryPc) or inRanges(cp, CategoryL) or inRanges(cp, CategoryM) or inRanges(cp, CategoryN) or cp in [0x200c, 0x200d]
  else: raise newException(ValueError, "[native tokenizer] unsupported Unicode property: " & category)

proc utf8Width*(text: string, at: int): int =
  let a = ord(text[at])
  if a < 128: return 1
  var n = 0
  if a in 0xc2..0xdf: n = 2
  elif a in 0xe0..0xef: n = 3
  elif a in 0xf0..0xf4: n = 4
  else: return 0
  if n > text.len-at: return 0
  for i in 1..<n:
    if (ord(text[at+i]) and 0xc0) != 0x80: return 0
  let b = ord(text[at+1])
  if (a == 0xe0 and b < 0xa0) or (a == 0xed and b >= 0xa0) or
     (a == 0xf0 and b < 0x90) or (a == 0xf4 and b >= 0x90): return 0
  n

proc utf8ErrorWidth*(text: string, at: int): tuple[consumed: int, incomplete: bool] =
  # Unicode maximal-subpart replacement, matching Rust's from_utf8_lossy.
  let lead = ord(text[at])
  let expected = if lead in 0xc2..0xdf: 2 elif lead in 0xe0..0xef: 3
                 elif lead in 0xf0..0xf4: 4 else: 1
  result.consumed = 1
  if expected == 1: return
  for i in 1..<expected:
    if at+i >= text.len:
      result.incomplete = true
      return
    let b = ord(text[at+i])
    if b notin 0x80..0xbf: return
    if i == 1 and ((lead == 0xe0 and b < 0xa0) or (lead == 0xed and b >= 0xa0) or
                   (lead == 0xf0 and b < 0x90) or (lead == 0xf4 and b >= 0x90)): return
    inc result.consumed

proc drainUtf8*(text: var string, final = false): string =
  var at = 0
  while at < text.len:
    let n = utf8Width(text, at)
    if n > 0:
      result.add(text[at..<at+n])
      at += n
    else:
      let error = utf8ErrorWidth(text, at)
      if error.incomplete and not final: break
      result.add("\xef\xbf\xbd")
      at += error.consumed
  if at > 0: text = text[at..^1]

proc validUtf8*(text: string): string =
  var pending = text
  drainUtf8(pending, final = true)

proc runeSpans*(text: string): seq[RuneSpan] =
  var at = 0
  while at < text.len:
    let n = utf8Width(text, at)
    if n == 0: raise newException(ValueError, "[native tokenizer] malformed UTF-8")
    result.add(RuneSpan(cp: int(runeAt(text, at)), start: at, finish: at+n))
    at += n

proc unicodeLower*(text: string): string =
  # Full per-character lowercase, including expansions such as U+0130 -> i + dot.
  # Tokenizers' Lowercase normalizer applies char::to_lowercase in the same way.
  for rune in text.runes:
    let cp = int(rune)
    var lo = 0
    var hi = LowercaseEntries.len
    var found = false
    while lo < hi:
      let mid = (lo+hi) div 2
      if cp < LowercaseEntries[mid][0]: hi = mid
      elif cp > LowercaseEntries[mid][0]: lo = mid+1
      else:
        result.add(LowercaseEntries[mid][1])
        found = true
        break
    if not found: result.add($rune)

proc unicodeStrip*(text: string, leading = true, trailing = true): string =
  let chars = runeSpans(text)
  var first = 0
  var last = chars.len
  if leading:
    while first < last and unicodeSpace(chars[first].cp): inc first
  if trailing:
    while last > first and unicodeSpace(chars[last-1].cp): dec last
  if first == last: return ""
  text[chars[first].start..<chars[last-1].finish]
