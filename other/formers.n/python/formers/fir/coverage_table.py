COVERAGE = {}
for _surface, _name, _status, _lowering, _blocker, _adapter in _ROWS:
    if _name in COVERAGE:
        raise ValueError("duplicate coverage entry: " + _name)
    if _status not in STATUSES:
        raise ValueError("unknown status for " + _name)
    COVERAGE[_name] = {"surface": _surface, "status": _status, "lowering": _lowering,
                       "blocker": _blocker, "adapter": _adapter}
del _surface, _name, _status, _lowering, _blocker, _adapter


def summary():
    """Counts per status, per surface, and per (surface, status)."""
    by_status = {s: 0 for s in STATUSES}
    by_surface = {k: 0 for k, _ in SURFACES}
    by_surface_status = {k: {s: 0 for s in STATUSES} for k, _ in SURFACES}
    adapter = {}
    for entry in COVERAGE.values():
        by_status[entry["status"]] += 1
        by_surface[entry["surface"]] += 1
        by_surface_status[entry["surface"]][entry["status"]] += 1
        adapter[entry["adapter"]] = adapter.get(entry["adapter"], 0) + 1
    return {"total": len(COVERAGE), "by_status": by_status, "by_surface": by_surface,
            "by_surface_status": by_surface_status, "adapter": adapter}


def items(surface=None, status=None):
    """Ordered (name, entry) pairs filtered by surface and/or status."""
    return [(k, v) for k, v in COVERAGE.items()
            if (surface is None or v["surface"] == surface) and (status is None or v["status"] == status)]


def surfaces():
    """Surface keys in document order."""
    return [k for k, _ in SURFACES]


def _cell(text):
    return text.replace("|", "\\|") if text else "–"


def markdown_summary():
    """The status and per-surface count tables and the from_torch line of docs/fir-script-coverage.md."""
    s = summary()
    lines = ["| Status | Items |", "| --- | --- |"]
    lines += ["| %s | %d |" % (k, s["by_status"][k]) for k in STATUSES]
    lines += ["| **total** | **%d** |" % s["total"], "",
              "| Surface | %s | total |" % " | ".join(STATUSES), "| --- |" + " --- |" * (len(STATUSES) + 1)]
    for key, title in SURFACES:
        counts = s["by_surface_status"][key]
        lines.append("| %s (`%s`) | %s | %d |" % (title, key, " | ".join(str(counts[k]) for k in STATUSES),
                                                 s["by_surface"][key]))
    adapter = ", ".join("%s %d" % (k, v) for k, v in sorted(s["adapter"].items()))
    lines += ["", "`fir.from_torch` acceptance over all items: %s." % adapter]
    return "\n".join(lines)


def markdown_table(surface):
    """The ``### <surface title>`` section of docs/fir-script-coverage.md."""
    title = dict(SURFACES)[surface]
    lines = ["### " + title, "", "| Item | Status | Lowering | Blocker / limit | from_torch |",
             "| --- | --- | --- | --- | --- |"]
    for name, e in items(surface):
        lines.append("| `%s` | %s | %s | %s | %s |" % (name, e["status"], _cell(e["lowering"]), _cell(e["blocker"]),
                                                       e["adapter"]))
    return "\n".join(lines)


def write_markdown(path):
    """Regenerate the summary and the coverage tables inside an existing coverage document."""
    from pathlib import Path
    path = Path(path)
    text = path.read_text(encoding="utf-8")
    def between(text, start, end, body):
        a = text.index(start) + len(start)
        b = text.index(end, a)
        return text[:a] + "\n\n" + body + "\n\n" + text[b:]
    text = between(text, "## Summary", "## Tracing semantics", markdown_summary())
    text = between(text, "## Coverage tables", "## Prioritized gaps",
                   "\n\n".join(markdown_table(k) for k in surfaces()))
    path.write_text(text, encoding="utf-8")


